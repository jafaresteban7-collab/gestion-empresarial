-- =============================================================================
-- GestiónPro · Origen de datos SQL en Supabase (PostgreSQL + API REST PostgREST)
--
-- profiles  1 ── 1 auth.users   (perfil y rol de cada usuario de Supabase Auth)
-- products                      (catálogo de inventario)
--
-- Seguridad: Row Level Security en ambas tablas. Leer exige sesión; crear,
-- editar y borrar productos exige rol 'admin', comprobado en la base de datos
-- y no en el navegador. Nadie puede cambiarse el rol desde la API.
-- =============================================================================

-- Perfiles ---------------------------------------------------------------------
create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  name        varchar(60)  not null check (char_length(trim(name)) >= 2),
  email       varchar(150) not null unique,
  department  varchar(40)  not null default 'Ventas',
  role        varchar(10)  not null default 'user' check (role in ('admin', 'user')),
  created_at  timestamptz  not null default now()
);

comment on table public.profiles is 'Perfil y rol (RBAC) de cada usuario de Supabase Auth.';

-- Cada alta en Supabase Auth crea su perfil como Usuario estándar
create function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, name, email, department)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)),
    lower(new.email),
    coalesce(nullif(new.raw_user_meta_data ->> 'department', ''), 'Ventas')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ¿El usuario de la petición actual es administrador? (lo usan las políticas RLS)
create function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Validación asíncrona del registro: ¿ya existe ese correo?
create function public.email_exists(p_email text)
returns boolean
language sql
stable
security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles where email = lower(trim(p_email)));
$$;

revoke execute on function public.is_admin() from anon;
grant execute on function public.email_exists(text) to anon, authenticated;

-- Productos --------------------------------------------------------------------
create table public.products (
  id          bigint generated by default as identity primary key,
  sku         varchar(6)    not null unique check (sku ~ '^[A-Z]{2}-[0-9]{3}$'),
  name        varchar(80)   not null check (char_length(trim(name)) >= 3),
  category    varchar(20)   not null check (category in ('Hardware', 'Software', 'Mobiliario', 'Consumibles')),
  stock       integer       not null check (stock >= 0),
  price       numeric(10,2) not null check (price >= 0),
  supplier    varchar(60)   not null default '',
  updated_at  timestamptz   not null default now()
);

comment on table public.products is 'Catálogo de inventario de GestiónPro.';

create function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger products_touch_updated_at
  before update on public.products
  for each row execute function public.touch_updated_at();

-- Permisos de la API -----------------------------------------------------------
revoke all on public.profiles, public.products from anon;
grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.products to authenticated;

-- Row Level Security -----------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.products enable row level security;

-- Cada usuario ve su perfil; el administrador ve todos (pantalla Usuarios)
create policy "profiles: propio o administrador"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_admin()));

-- Cualquier usuario con sesión consulta el catálogo
create policy "products: lectura con sesión"
  on public.products for select to authenticated
  using (true);

-- Solo el administrador crea, edita y borra
create policy "products: alta solo administrador"
  on public.products for insert to authenticated
  with check ((select public.is_admin()));

create policy "products: edición solo administrador"
  on public.products for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "products: borrado solo administrador"
  on public.products for delete to authenticated
  using ((select public.is_admin()));
